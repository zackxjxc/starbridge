  let preference = 'system';
  try { const saved = localStorage.getItem(storageKey); if (valid(saved)) preference = saved; } catch { /* Storage may be disabled. */ }
  const systemLocale = () => /^zh(?:-|$)/i.test(navigator.languages?.[0] || navigator.language || '') ? 'zh-CN' : 'en';
  const locale = () => preference === 'system' ? systemLocale() : preference;
  const format = (text, values) => text.replace(/\{(\d+)\}/g, (match, index) => index < values.length ? String(values[index]) : match);
  const t = (source, ...values) => format(locale() === 'en' ? translations[source] ?? source : source, values);
  const escape = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  function pattern(template) {
    const indexes = [];
    const parts = template.split(/(\{\d+\})/g).map(part => {
      const match = /^\{(\d+)\}$/.exec(part);
      if (!match) return escape(part);
      indexes.push(Number(match[1])); return '([\\s\\S]*?)';
    });
    return { regex: new RegExp('^' + parts.join('') + '$'), indexes };
  }
  const rules = Object.entries(translations).map(([zh, en]) => ({ zh, en, forward: pattern(zh), reverse: pattern(en) }))
    .sort((a, b) => b.zh.replace(/\{\d+\}/g, '').length - a.zh.replace(/\{\d+\}/g, '').length);
  function translateMessage(value, toSource = false) {
    const text = String(value ?? '');
    for (const rule of rules) {
      const from = toSource ? rule.reverse : rule.forward;
      const match = from.regex.exec(text);
      if (!match) continue;
      const values = [];
      from.indexes.forEach((index, capture) => { values[index] = match[capture + 1]; });
      return format(toSource ? rule.zh : locale() === 'en' ? rule.en : rule.zh, values);
    }
    return text;
  }
