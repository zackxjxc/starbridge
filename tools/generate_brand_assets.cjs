#!/usr/bin/env node
'use strict';

// Authoring only: npm install --prefix .cache/brand-assets --no-save --no-package-lock sharp
// Run: node tools/generate_brand_assets.cjs [--check]
const fs = require('node:fs');
const path = require('node:path');

const repo = path.resolve(__dirname, '..');
let sharp;
try {
  sharp = require('sharp');
} catch {
  try {
    sharp = require(path.join(repo, '.cache/brand-assets/node_modules/sharp'));
  } catch {
    throw new Error('Install sharp first: npm install --prefix .cache/brand-assets --no-save --no-package-lock sharp');
  }
}

const check = process.argv.includes('--check');
const source = fs.readFileSync(path.join(repo, 'client/icons/logo.svg'), 'utf8');
const geometry = source.match(/<path\b[^>]*\bd="([^"]+)"/);
if (!geometry || !source.includes('viewBox="0 0 256 112"')) {
  throw new Error('Expected the single-path bridge master with viewBox 0 0 256 112');
}
const mark = `<path fill="white" fill-rule="evenodd" d="${geometry[1]}"/>`;
const app = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">
  <title>StarBridge</title>
  <rect width="256" height="256" rx="56" fill="#4e5a6a"/>
  <g transform="translate(23.04 82.08) scale(.82)">${mark}</g>
</svg>\n`;
const mask = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 112">${mark}</svg>`;
const maskUrl = `url("data:image/svg+xml,${encodeURIComponent(mask)}") center / contain no-repeat`;
const favicon = `  <!-- starbridge-favicon:start -->
  <link rel="icon" type="image/svg+xml" href="data:image/svg+xml,${encodeURIComponent(app.trim())}">
  <!-- starbridge-favicon:end -->`;
const brand = `/* starbridge-brand:start (generated by tools/generate_brand_assets.cjs) */
.brand-mark { width: 20px; height: 20px; border-radius: 5px; display: flex; align-items: center; justify-content: center; flex-shrink: 0; background: var(--main); color: var(--on); font-size: 0; }
.brand-mark::before { content: ""; width: 18px; height: 12px; background: currentColor; -webkit-mask: ${maskUrl}; mask: ${maskUrl}; }
/* starbridge-brand:end */`;
const adminBrand = `    /* starbridge-brand:start (generated by tools/generate_brand_assets.cjs) */
    .admin-brand { display:flex; align-items:center; gap:12px; }
    .admin-brand::before { content:""; width:36px; height:24px; flex-shrink:0; background:currentColor; -webkit-mask:${maskUrl}; mask:${maskUrl}; }
    /* starbridge-brand:end */`;

function replaceOnce(text, pattern, replacement, label) {
  const matches = [...text.matchAll(new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : pattern.flags + 'g'))];
  if (matches.length !== 1) throw new Error(`Expected one ${label}, found ${matches.length}`);
  return text.replace(pattern, () => replacement);
}

function withFavicon(html) {
  if (html.includes('<!-- starbridge-favicon:start -->')) {
    return replaceOnce(html, /^  <!-- starbridge-favicon:start -->[\s\S]*?<!-- starbridge-favicon:end -->/m, favicon, 'favicon block');
  }
  return replaceOnce(html, /^  <title>[^\n]+<\/title>/m, html.match(/^  <title>[^\n]+<\/title>/m)?.[0] + '\n' + favicon, 'document title');
}

function ico(entries) {
  const header = Buffer.alloc(6 + entries.length * 16);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(entries.length, 4);
  let offset = header.length;
  entries.forEach(({ size, png }, index) => {
    const base = 6 + index * 16;
    header[base] = size === 256 ? 0 : size;
    header[base + 1] = size === 256 ? 0 : size;
    header.writeUInt16LE(1, base + 4);
    header.writeUInt16LE(32, base + 6);
    header.writeUInt32LE(png.length, base + 8);
    header.writeUInt32LE(offset, base + 12);
    offset += png.length;
  });
  return Buffer.concat([header, ...entries.map(entry => entry.png)]);
}

function icns(entries) {
  // PNG-backed Retina sizes and legacy-size aliases, decoded by macOS and Pillow.
  const types = { icp4:16, icp5:32, icp6:64, ic07:128, ic08:256, ic09:512, ic10:1024, ic11:32, ic12:64, ic13:256, ic14:512 };
  const chunks = Object.entries(types).map(([type, size]) => {
    const png = entries.get(size);
    const header = Buffer.alloc(8);
    header.write(type, 0, 4, 'ascii');
    header.writeUInt32BE(png.length + 8, 4);
    return Buffer.concat([header, png]);
  });
  const header = Buffer.alloc(8);
  header.write('icns', 0, 4, 'ascii');
  header.writeUInt32BE(8 + chunks.reduce((sum, chunk) => sum + chunk.length, 0), 4);
  return Buffer.concat([header, ...chunks]);
}

async function main() {
  const outputs = new Map();
  const entries = new Map();
  for (const size of [16, 24, 32, 48, 64, 128, 256, 512, 1024]) {
    const png = await sharp(Buffer.from(app)).resize(size, size).png().toBuffer();
    entries.set(size, png);
  }
  outputs.set('client/icons/app-icon.svg', app);
  outputs.set('client/icons/icon.png', entries.get(1024));
  outputs.set('client/icons/icon.ico', ico([16, 24, 32, 48, 64, 128, 256].map(size => ({ size, png: entries.get(size) }))));
  outputs.set('client/icons/icon.icns', icns(entries));

  const css = fs.readFileSync(path.join(repo, 'client-ui/style.css'), 'utf8');
  outputs.set('client-ui/style.css', css.includes('/* starbridge-brand:start')
    ? replaceOnce(css, /^\/\* starbridge-brand:start[^\n]*[\s\S]*?\/\* starbridge-brand:end \*\//m, brand, 'client brand block')
    : replaceOnce(css, /^\.brand-mark \{[^\n]+\}/m, brand, 'client brand rule'));
  outputs.set('client-ui/index.html', withFavicon(fs.readFileSync(path.join(repo, 'client-ui/index.html'), 'utf8')));
  let admin = withFavicon(fs.readFileSync(path.join(repo, 'admin-ui/index.html'), 'utf8'));
  admin = admin.includes('/* starbridge-brand:start')
    ? replaceOnce(admin, /^    \/\* starbridge-brand:start[^\n]*[\s\S]*?\/\* starbridge-brand:end \*\//m, adminBrand, 'admin brand block')
    : replaceOnce(admin, /^  <\/style>/m, adminBrand + '\n  </style>', 'admin styles');
  if (!admin.includes('<h1 class="admin-brand">')) {
    admin = replaceOnce(admin, /<h1>StarBridge 管理台<\/h1>/, '<h1 class="admin-brand">StarBridge 管理台</h1>', 'admin heading');
  }
  outputs.set('admin-ui/index.html', admin);

  const stale = [];
  for (const [name, content] of outputs) {
    const target = path.join(repo, name);
    const bytes = Buffer.isBuffer(content) ? content : Buffer.from(content, 'utf8');
    if (fs.existsSync(target) && fs.readFileSync(target).equals(bytes)) continue;
    stale.push(name);
    if (!check) fs.writeFileSync(target, bytes);
  }
  if (check && stale.length) throw new Error(`Stale brand assets:\n${stale.join('\n')}`);
  console.log(check ? `Verified ${outputs.size} generated brand assets` : `Updated ${stale.length} brand assets`);
}

main().catch(error => { console.error(error.message); process.exitCode = 1; });
